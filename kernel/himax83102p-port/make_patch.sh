#!/bin/sh
# На сборочном хосте: собрать kernel/patches/0006 из порта (out/) + Kconfig/Makefile + DTS.
# $1 = дерево ядра с применёнными 0001–0005 (не изменённое, кроме DTS), $2 = каталог порта, $3 = DTS (новый), $4 = DTS (как после 0005)
set -e
K=$1; P=$2; NEW_DTS=$3; OLD_DTS=$4; T=$(mktemp -d)
D=drivers/input/touchscreen; DTS=arch/arm64/boot/dts/qcom/sm6115p-lenovo-j606f-hx83102p.dts
mkdir -p $T/a/$D $T/b/$D/himax_hx83102e $T/a/$(dirname $DTS) $T/b/$(dirname $DTS)
cp $K/$D/Kconfig $K/$D/Makefile $T/a/$D/
cp $K/$D/Kconfig $K/$D/Makefile $T/b/$D/
cp $P/out/*.c $P/out/*.h $P/kernel/Kconfig $P/kernel/Makefile $T/b/$D/himax_hx83102e/
# Kconfig: перед "endif" раздела тачскринов; Makefile: в конец
python3 - $T/b/$D/Kconfig $T/b/$D/Makefile <<'PY'
import sys
k, m = sys.argv[1], sys.argv[2]
s = open(k).read(); i = s.rfind("\nendif")
s = s[:i] + '\nsource "drivers/input/touchscreen/himax_hx83102e/Kconfig"\n' + s[i:]
open(k, "w").write(s)
open(m, "a").write("obj-$(CONFIG_TOUCHSCREEN_HIMAX_HX83102E)\t+= himax_hx83102e/\n")
PY
cp $OLD_DTS $T/a/$DTS; cp $NEW_DTS $T/b/$DTS
cd $T && { cat <<'HDR'
From: Yar1klamer
Subject: [PATCH] Input: add Himax HX83102E touchscreen (Lenovo TB-J606F), DT node

Port of the GPL Himax "hxchipset" driver from the Lenovo TB-J606F 4.19 kernel
(github.com/adazem009/kernel_lenovo_tbj606, drivers/input/touchscreen/himax83102p)
to 7.2: single module, no debug/inspection, gpiod lookup, proc_ops, timespec64,
drm_panel_follower instead of the downstream panel notifier, touchscreen-inverted-x/y.
Generated by himax83102p-port/port.py.
---
HDR
diff -ruN a b || true; } > /tmp/0006.patch
rm -rf $T; echo /tmp/0006.patch
