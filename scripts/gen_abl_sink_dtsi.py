#!/usr/bin/env python3
"""Генерирует sm6115p-lenovo-j606f-abl-sink.dtsi: тот же «отстойник», что dtb_add_abl_sink.py, но в исходнике DTS,
чтобы обычная сборка ядра (dtbs) сразу давала DTB, который ABL примет вместе со стоковым dtbo.
phandle задаются явно с 0xa0001, чтобы не пересечься с phandle, которые dtc раздаёт сам (с 1 и выше).
Запуск: python3 -I scripts/gen_abl_sink_dtsi.py raw/dtbo_a/labels_445.txt > src/dts/sm6115p-lenovo-j606f-abl-sink.dtsi"""
import sys
labels = [l.strip() for l in open(sys.argv[1]) if l.strip()]
out = ["// SPDX-License-Identifier: (GPL-2.0+ OR BSD-3-Clause)",
       "/*",
       " * Lenovo ABL always applies the stock dtbo overlay (\"Lenovo P11 WIFI PVT\") to the",
       " * DTB from boot.img and refuses to boot if the overlay's __fixups__ cannot be resolved.",
       " * Give every label the stock overlay references a dummy node inside a disabled,",
       " * compatible-less container, so the overlay lands there and nothing probes it.",
       " * Generated by scripts/gen_abl_sink_dtsi.py from the stock dtbo, do not edit.",
       " */", "", "/ {", "\tabl-sink {", '\t\tstatus = "disabled";', ""]
for i, l in enumerate(labels):
    out += [f"\t\t{l} {{", f"\t\t\tphandle = <{0xa0001 + i:#x}>;", "\t\t};"]
out += ["\t};", "", "\t__symbols__ {"]
out += [f'\t\t{l} = "/abl-sink/{l}";' for l in labels]
out += ["\t};", "};", ""]
print("\n".join(out))
